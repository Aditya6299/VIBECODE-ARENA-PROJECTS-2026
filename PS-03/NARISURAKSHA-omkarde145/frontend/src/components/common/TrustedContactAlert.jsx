import React, { useState } from 'react';
import { useCase } from '../../context/CaseContext';
import { Mail, UserCheck, X, Send, ShieldCheck } from 'lucide-react';

export const TrustedContactAlert = () => {
  const { intakeData, evidenceFiles, timelineEvents, simulatedSubmission, lang } = useCase();
  const [isOpen, setIsOpen] = useState(false);
  const [contactEmail, setContactEmail] = useState('');
  const [contactName, setContactName] = useState('');

  const sendAlert = () => {
    if (!contactEmail) return;

    const trackingId = simulatedSubmission?.trackingId || 'NCR-2026-PENDING';
    const evidenceCount = evidenceFiles.length;
    const timelineCount = timelineEvents.length;

    const subject = encodeURIComponent(`[NariSuraksha AI] Urgent: Cyber Abuse Evidence Alert - Ref ${trackingId}`);

    const body = encodeURIComponent(`Dear ${contactName || 'Trusted Contact'},

I am reaching out to you because I need your support regarding a cyber harassment and morphed image abuse incident I am currently experiencing.

I have used the NariSuraksha AI platform (https://narisuraksha.ai) to document the incident and compile a Section 65B-compliant evidence dossier.

Case Reference ID: ${trackingId}
Evidence Files Hashed (SHA-256): ${evidenceCount}
Timeline Events Recorded: ${timelineCount}
Affected Platforms: ${Array.isArray(intakeData.platforms) ? intakeData.platforms.join(', ') : 'Not specified'}

I need help submitting this dossier to the National Cyber Crime Reporting Portal at https://cybercrime.gov.in.

Emergency Helplines:
- National Cyber Crime: 1930
- Women Helpline: 1091

Please keep this confidential and reach out to me directly.

This message was generated by NariSuraksha AI. No personal images or sensitive files are attached to this email.`);

    window.open(`mailto:${contactEmail}?subject=${subject}&body=${body}`, '_blank');
    setIsOpen(false);
  };

  return (
    <>
      <button
        onClick={() => setIsOpen(true)}
        className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-indigo-600/20 hover:bg-indigo-600/30 border border-indigo-500/40 text-indigo-300 text-xs font-semibold transition-all"
        title={lang === 'hi' ? 'विश्वसनीय संपर्क को सतर्क करें' : 'Alert a Trusted Contact'}
      >
        <UserCheck className="w-3.5 h-3.5" />
        <span className="hidden sm:inline">{lang === 'hi' ? 'संपर्क सतर्क करें' : 'Alert Contact'}</span>
      </button>

      {isOpen && (
        <div className="fixed inset-0 bg-black/80 backdrop-blur-md flex items-center justify-center p-4 z-50">
          <div className="bg-slate-900 border border-indigo-500/30 rounded-2xl p-6 max-w-md w-full shadow-2xl space-y-4">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <div className="p-2 rounded-xl bg-indigo-500/20">
                  <UserCheck className="w-5 h-5 text-indigo-400" />
                </div>
                <div>
                  <h3 className="text-sm font-bold text-white">
                    {lang === 'hi' ? 'विश्वसनीय संपर्क सतर्क करें' : 'Alert Trusted Contact'}
                  </h3>
                  <p className="text-[11px] text-slate-400">
                    {lang === 'hi' ? 'कोई फ़ाइल या तस्वीर ईमेल से नहीं भेजी जाती' : 'No files or images are sent via email'}
                  </p>
                </div>
              </div>
              <button onClick={() => setIsOpen(false)} className="p-1 text-slate-400 hover:text-white">
                <X className="w-4 h-4" />
              </button>
            </div>

            <div className="bg-indigo-950/30 border border-indigo-500/20 rounded-xl p-3 text-[11px] text-indigo-200 flex items-start gap-2">
              <ShieldCheck className="w-4 h-4 text-indigo-400 flex-shrink-0 mt-0.5" />
              <span>
                {lang === 'hi'
                  ? 'यह ईमेल केवल पाठ-आधारित सारांश भेजेगा — आपकी कोई भी तस्वीर, स्क्रीनशॉट या हैश ईमेल में नहीं जाएगी।'
                  : 'This sends a text-only summary via your default mail app — no images, screenshots, or hashes are included in the email.'}
              </span>
            </div>

            <div className="space-y-3">
              <div>
                <label className="block text-[11px] font-semibold text-slate-300 mb-1">
                  {lang === 'hi' ? 'संपर्क का नाम' : "Contact's Name"}
                </label>
                <input
                  type="text"
                  value={contactName}
                  onChange={(e) => setContactName(e.target.value)}
                  placeholder={lang === 'hi' ? 'जैसे: माँ, अनिता दीदी' : 'e.g. Mom, Lawyer Ritu'}
                  className="w-full bg-slate-950 border border-slate-800 rounded-xl px-3 py-2 text-xs text-white placeholder-slate-500 focus:outline-none focus:border-indigo-500"
                />
              </div>
              <div>
                <label className="block text-[11px] font-semibold text-slate-300 mb-1">
                  {lang === 'hi' ? 'ईमेल पता *' : 'Email Address *'}
                </label>
                <input
                  type="email"
                  value={contactEmail}
                  onChange={(e) => setContactEmail(e.target.value)}
                  placeholder="trusted.contact@example.com"
                  className="w-full bg-slate-950 border border-slate-800 rounded-xl px-3 py-2 text-xs text-white placeholder-slate-500 focus:outline-none focus:border-indigo-500 font-mono"
                />
              </div>
            </div>

            <div className="flex gap-3 pt-1">
              <button
                onClick={() => setIsOpen(false)}
                className="flex-1 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium border border-slate-700"
              >
                {lang === 'hi' ? 'रद्द करें' : 'Cancel'}
              </button>
              <button
                onClick={sendAlert}
                disabled={!contactEmail}
                className="flex-1 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-bold flex items-center justify-center gap-1.5 disabled:opacity-40 disabled:cursor-not-allowed"
              >
                <Send className="w-3.5 h-3.5" />
                <span>{lang === 'hi' ? 'ईमेल खोलें' : 'Open Email'}</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
};
